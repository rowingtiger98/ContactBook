<?php
/*-------------------------------------------------------------*/
/*                                                             */
/*  ENTRY FUNCTIONS                                            */
/*                                                             */
/*  Book entries (CB_Book_Entry) - the information a visitor   */
/*  adds to someone's contact book from add_entry.php. Each    */
/*  entry gets its own UUID (ENTRY_UUID) and points at its     */
/*  book through ENTRY_Book_Parent_UUID = CB_Book_UUID.        */
/*  Photos added with an entry are saved in                    */
/*  books/<book uuid>/pictures/<entry uuid>/photo-1.jpg, ...   */
/*                                                             */
/*  Each new entry also gets a secret edit code. The person    */
/*  who made it is emailed a link with the code                */
/*  (edit_my_entry.php) so they can change their own entry;    */
/*  only a SHA-256 hash of the code is saved, in               */
/*  ENTRY_Edit_Token. The link doesn't expire.                 */
/*                                                             */
/*  Everything is saved with prepared statements and must be   */
/*  escaped with htmlspecialchars() wherever it's shown.       */
/*                                                             */
/*-------------------------------------------------------------*/
require_once __DIR__ . '/bookFunctions.php';
require_once __DIR__ . '/mailFunctions.php';

const ENTRY_NAME_MAX_LENGTH    = 64;    // ENTRY_Name VARCHAR(64)
const ENTRY_STREET_MAX_LENGTH  = 128;   // ENTRY_Street_Address VARCHAR(128)
const ENTRY_CITY_MAX_LENGTH    = 64;    // ENTRY_City VARCHAR(64)
const ENTRY_STATE_MAX_LENGTH   = 64;    // ENTRY_State VARCHAR(64)
const ENTRY_ZIP_MAX_LENGTH     = 16;    // ENTRY_Zip is VARCHAR(64); real postal codes are far shorter
const ENTRY_PHONE_MAX_LENGTH   = 32;    // ENTRY_Phone VARCHAR(32)
const ENTRY_EMAILS_MAX_LENGTH  = 512;   // ENTRY_Emails VARCHAR(512), all addresses together
const ENTRY_EMAILS_MAX_COUNT   = 5;     // keep in step with add_entry.js
const ENTRY_EMAIL_SEPARATOR    = ', ';  // how the addresses are joined in ENTRY_Emails
const ENTRY_NOTES_MAX_LENGTH   = 2000;
const ENTRY_PHOTOS_MAX_COUNT   = 5;     // keep in step with add_entry.js; each up to BOOK_PHOTO_MAX_BYTES
const ENTRY_EDIT_TOKEN_BYTES   = 32;    // edit code in the emailed link: 64 hex characters

/* *********************************************************** */
/* Function:    find_book_by_uuid                              */
/* Description: Looks up the book an entry is being added to.  */
/* Inputs:      $uuid - the CB_Book_UUID from the link.        */
/* Returns:     The row (CB_Book_UUID, CB_Book_Name_About,     */
/*              CB_Book_Description), or null if there's no    */
/*              such book.                                     */
/* *********************************************************** */
function find_book_by_uuid(string $uuid): ?array {
    // Only ever generated by generate_uuid_v4(), so anything else can't match.
    if (!preg_match('/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/', $uuid)) {
        return null;
    }
    $connection = Create_SQL_PHP_DataObject();
    $stmt = $connection->prepare(
        'SELECT CB_Book_UUID, CB_Book_Name_About, CB_Book_Description
         FROM CB_Created_Books WHERE CB_Book_UUID = ?'
    );
    $stmt->execute([$uuid]);
    $book = $stmt->fetch();
    $stmt = null;
    $connection = null;
    return $book ?: null;
}

/* *********************************************************** */
/* Function:    clean_entry_line                               */
/* Description: Tidies a one-line field: runs of whitespace    */
/*              (including newlines and tabs) become single    */
/*              spaces and control characters are removed.     */
/* Returns:     The trimmed text.                              */
/* *********************************************************** */
function clean_entry_line($value): string {
    if (!is_string($value)) {
        return '';
    }
    $value = preg_replace('/\s+/u', ' ', $value) ?? '';
    $value = preg_replace('/\p{Cc}/u', '', $value) ?? '';
    return trim($value);
}

/* *********************************************************** */
/* Function:    clean_entry_emails                             */
/* Description: Takes the email boxes from the form, trims     */
/*              them and drops the empty ones.                 */
/* Returns:     The list of addresses entered.                 */
/* *********************************************************** */
function clean_entry_emails($emails): array {
    if (!is_array($emails)) {
        $emails = [$emails];
    }
    $clean = [];
    foreach ($emails as $email) {
        $email = clean_entry_line($email);
        if ($email !== '') {
            $clean[] = $email;
        }
    }
    return $clean;
}

/* *********************************************************** */
/* Function:    clean_entry_form                               */
/* Description: Pulls the entry fields out of the submitted    */
/*              form and tidies each one.                      */
/* Inputs:      $form - the submitted fields ($_POST).         */
/* Returns:     ['name', 'street', 'city', 'state', 'zip',     */
/*               'phone' => string, 'emails' => string[],      */
/*               'notes' => string]                            */
/* *********************************************************** */
function clean_entry_form(array $form): array {
    return [
        'name'   => clean_entry_line($form['entry_name'] ?? ''),
        'street' => clean_entry_line($form['entry_street'] ?? ''),
        'city'   => clean_entry_line($form['entry_city'] ?? ''),
        'state'  => clean_entry_line($form['entry_state'] ?? ''),
        'zip'    => clean_entry_line($form['entry_zip'] ?? ''),
        'phone'  => clean_entry_line($form['entry_phone'] ?? ''),
        'emails' => clean_entry_emails($form['entry_emails'] ?? []),
        'notes'  => clean_book_description(is_string($form['entry_notes'] ?? null) ? $form['entry_notes'] : ''),
    ];
}

/* *********************************************************** */
/* Function:    validate_entry                                 */
/* Description: Checks the cleaned fields of an entry. The    */
/*              name and at least one email are required.      */
/* Inputs:      $entry - the array from clean_entry_form().    */
/* Returns:     An error message, or '' if everything is OK.   */
/* *********************************************************** */
function validate_entry(array $entry): string {
    if ($entry['name'] === '') {
        return 'Please enter your name.';
    }
    if (mb_strlen($entry['name'], 'UTF-8') > ENTRY_NAME_MAX_LENGTH) {
        return 'Your name can be at most ' . ENTRY_NAME_MAX_LENGTH . ' characters.';
    }
    // Same rule as book names: letters in any language, digits and name punctuation.
    if (!preg_match("/^[\p{L}\p{M}0-9 .,'’()&-]+$/u", $entry['name'])) {
        return 'Your name can only contain letters, numbers, spaces and . , \' - ( ) &';
    }

    $lengths = [
        'street' => [ENTRY_STREET_MAX_LENGTH, 'The street address'],
        'city'   => [ENTRY_CITY_MAX_LENGTH,   'The city'],
        'state'  => [ENTRY_STATE_MAX_LENGTH,  'The state'],
        'zip'    => [ENTRY_ZIP_MAX_LENGTH,    'The zip code'],
        'phone'  => [ENTRY_PHONE_MAX_LENGTH,  'The phone number'],
    ];
    foreach ($lengths as $field => [$max, $label]) {
        if (mb_strlen($entry[$field], 'UTF-8') > $max) {
            return "{$label} can be at most {$max} characters.";
        }
    }
    // Addresses are free text but never need markup characters.
    foreach (['street' => 'The street address', 'city' => 'The city', 'state' => 'The state'] as $field => $label) {
        if (preg_match('/[<>{}\[\]\\\\|^`~$=;"]/u', $entry[$field])) {
            return "{$label} contains characters that aren't allowed.";
        }
    }
    // Letters too, for postcodes like "SW1A 1AA" or "K1A 0B1".
    if ($entry['zip'] !== '' && !preg_match('/^[\p{L}0-9 -]+$/u', $entry['zip'])) {
        return 'The zip code can only contain letters, numbers, spaces and dashes.';
    }
    if ($entry['phone'] !== '') {
        if (!preg_match('/^[0-9 +().\/-]+(\s*(x|ext\.?)\s*[0-9]+)?$/i', $entry['phone'])
            || preg_match_all('/[0-9]/', $entry['phone']) < 7) {
            return 'Please enter a phone number with at least 7 digits, e.g. (555) 123-4567.';
        }
    }

    if ($entry['emails'] === []) {
        return 'Please enter an email address.';
    }
    if (count($entry['emails']) > ENTRY_EMAILS_MAX_COUNT) {
        return 'You can enter at most ' . ENTRY_EMAILS_MAX_COUNT . ' email addresses.';
    }
    foreach ($entry['emails'] as $email) {
        // A comma would break the list stored in ENTRY_Emails.
        if (filter_var($email, FILTER_VALIDATE_EMAIL) === false || strpos($email, ',') !== false) {
            return '"' . $email . '" is not a valid email address.';
        }
    }
    if (strlen(implode(ENTRY_EMAIL_SEPARATOR, $entry['emails'])) > ENTRY_EMAILS_MAX_LENGTH) {
        return 'Your email addresses are too long all together. Please remove one.';
    }

    if (mb_strlen($entry['notes'], 'UTF-8') > ENTRY_NOTES_MAX_LENGTH) {
        return 'The notes can be at most ' . ENTRY_NOTES_MAX_LENGTH . ' characters.';
    }
    return '';
}

/* *********************************************************** */
/* Function:    check_entry_photo_uploads                      */
/* Description: Checks the photos chosen in the form's         */
/*              multi-file box ($_FILES['entry_photos']), each */
/*              one with the same rules as a book's photo.     */
/* Inputs:      $files - the $_FILES entry, or null.           */
/* Returns:     ['error' => string, 'photos' => list of        */
/*               ['tmp' => string, 'type' => IMAGETYPE_*]]     */
/* *********************************************************** */
function check_entry_photo_uploads(?array $files): array {
    if ($files === null || !isset($files['error'])) {
        return ['error' => '', 'photos' => []];  // photos are optional
    }
    if (!is_array($files['error'])) {
        return ['error' => 'The photos could not be uploaded. Please try again.', 'photos' => []];
    }

    $photos = [];
    foreach (array_keys($files['error']) as $i) {
        $file = [];
        foreach (['name', 'tmp_name', 'error', 'size'] as $key) {
            $file[$key] = $files[$key][$i] ?? null;
        }
        if (!is_int($file['error'])) {
            return ['error' => 'The photos could not be uploaded. Please try again.', 'photos' => []];
        }
        if ($file['error'] === UPLOAD_ERR_NO_FILE) {
            continue;  // an empty box
        }
        if (count($photos) === ENTRY_PHOTOS_MAX_COUNT) {
            return ['error' => 'You can add at most ' . ENTRY_PHOTOS_MAX_COUNT . ' photos.', 'photos' => []];
        }
        $upload = check_book_photo_upload($file);
        if ($upload['error'] !== '') {
            $name = is_string($file['name']) ? clean_entry_line($file['name']) : '';
            return ['error' => ($name !== '' ? $name . ': ' : '') . $upload['error'], 'photos' => []];
        }
        $photos[] = ['tmp' => $upload['tmp'], 'type' => $upload['type']];
    }
    return ['error' => '', 'photos' => $photos];
}

/* *********************************************************** */
/* Function:    save_entry_photos                              */
/* Description: Creates books/<book>/pictures/<entry>/ and     */
/*              saves the photos in it as photo-1.jpg, ...     */
/*              (re-encoded like a book's photo - upright,     */
/*              resized, GPS and other hidden data removed).   */
/*              The book's .htaccess covers this folder too.   */
/* Inputs:      $book_uuid, $entry_uuid - the two UUIDs.       */
/*              $photos - from check_entry_photo_uploads().    */
/* Returns:     The entry's photo directory, or '' on failure  */
/*              (anything half-made is removed again).         */
/* *********************************************************** */
function save_entry_photos(string $book_uuid, string $entry_uuid, array $photos): string {
    $book_path     = book_directory_path($book_uuid);
    $pictures_path = $book_path . '/' . BOOK_PICTURES_DIR_NAME;
    $entry_path    = $pictures_path . '/' . $entry_uuid;

    if (!is_dir($book_path)) {
        error_log('ContactBook: book directory is missing: ' . $book_path);
        return '';
    }
    // Books created before pictures/ existed get it the first time it's needed.
    if (!is_dir($pictures_path) && !mkdir($pictures_path, 0755)) {
        error_log('ContactBook: could not create pictures directory ' . $pictures_path);
        return '';
    }
    if (!mkdir($entry_path, 0755)) {
        error_log('ContactBook: could not create entry photo directory ' . $entry_path);
        return '';
    }

    foreach ($photos as $i => $photo) {
        if (save_book_photo($photo['tmp'], $photo['type'], $entry_path, 'photo-' . ($i + 1)) === '') {
            error_log('ContactBook: could not save photo ' . ($i + 1) . ' for entry ' . $entry_uuid);
            remove_entry_photo_directory($entry_path);
            return '';
        }
    }
    return $entry_path;
}

/* *********************************************************** */
/* Function:    remove_entry_photo_directory                   */
/* Description: Removes an entry's photo directory and the     */
/*              photos save_entry_photos() put in it.          */
/* Inputs:      $dir - the entry's full photo directory path.  */
/* Returns:     Nothing                                        */
/* *********************************************************** */
function remove_entry_photo_directory(string $dir): void {
    foreach (glob($dir . '/photo-*') ?: [] as $file) {
        unlink($file);
    }
    rmdir($dir);
}

/* *********************************************************** */
/* Function:    create_entry                                   */
/* Description: Cleans, checks and saves a new entry in        */
/*              CB_Book_Entry for the given book, along with   */
/*              any photos. If the row can't be saved, the     */
/*              photos are removed again.                      */
/* Inputs:      $book_uuid - CB_Book_UUID of the book (already */
/*              checked with find_book_by_uuid()).             */
/*              $form - the submitted fields ($_POST).         */
/*              $photo_files - $_FILES['entry_photos'], or     */
/*              null.                                          */
/* Returns:     ['success' => bool, 'error' => string,         */
/*               'entry' => the cleaned fields, to refill the  */
/*               form after an error, and on success           */
/*               'entry_uuid' and 'edit_token' - the secret    */
/*               code for the person's edit link]              */
/* *********************************************************** */
function create_entry(string $book_uuid, array $form, ?array $photo_files = null): array {
    $entry = clean_entry_form($form);

    $error = validate_entry($entry);
    if ($error === '') {
        $uploads = check_entry_photo_uploads($photo_files);
        $error   = $uploads['error'];
    }
    if ($error !== '') {
        return ['success' => false, 'error' => $error, 'entry' => $entry];
    }

    $entry_uuid = generate_uuid_v4();
    $edit_token = bin2hex(random_bytes(ENTRY_EDIT_TOKEN_BYTES));
    $photo_path = '';
    if ($uploads['photos']) {
        $photo_path = save_entry_photos($book_uuid, $entry_uuid, $uploads['photos']);
        if ($photo_path === '') {
            return ['success' => false, 'error' => 'Your photos could not be saved. Please try again, or try different photos.', 'entry' => $entry];
        }
    }

    $null_if_empty = function (string $value): ?string {
        return ($value === '') ? null : $value;
    };

    try {
        $connection = Create_SQL_PHP_DataObject();
        $stmt = $connection->prepare(
            'INSERT INTO CB_Book_Entry
                (ENTRY_UUID, ENTRY_Book_Parent_UUID, ENTRY_Name, ENTRY_Emails, ENTRY_Street_Address,
                 ENTRY_City, ENTRY_State, ENTRY_Zip, ENTRY_Phone, ENTRY_Notes, ENTRY_Edit_Token)
             VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)'
        );
        $stmt->execute([
            $entry_uuid,
            $book_uuid,
            $entry['name'],
            $null_if_empty(implode(ENTRY_EMAIL_SEPARATOR, $entry['emails'])),
            $null_if_empty($entry['street']),
            $null_if_empty($entry['city']),
            $null_if_empty($entry['state']),
            $null_if_empty($entry['zip']),
            $null_if_empty($entry['phone']),
            $null_if_empty($entry['notes']),
            hash('sha256', $edit_token),
        ]);
        $stmt = null;
        $connection = null;
    } catch (PDOException $e) {
        error_log('ContactBook: could not save entry for book ' . $book_uuid . ': ' . $e->getMessage());
        if ($photo_path !== '') {
            remove_entry_photo_directory($photo_path);
        }
        return ['success' => false, 'error' => 'Your information could not be saved. Please try again.', 'entry' => $entry];
    }

    return ['success' => true, 'error' => '', 'entry' => $entry, 'entry_uuid' => $entry_uuid, 'edit_token' => $edit_token];
}

/* *********************************************************** */
/* Function:    list_book_entries                              */
/* Description: Every entry in a book, oldest first, with how  */
/*              many photos each one has (counted from its     */
/*              pictures/<entry uuid>/ folder).                */
/* Inputs:      $book_uuid - the book's CB_Book_UUID.          */
/* Returns:     Rows with ENTRY_UUID, ENTRY_Name, ENTRY_Emails,*/
/*              ENTRY_Phone, ENTRY_Notes and photo_count.      */
/* *********************************************************** */
function list_book_entries(string $book_uuid): array {
    $connection = Create_SQL_PHP_DataObject();
    $stmt = $connection->prepare(
        'SELECT ENTRY_UUID, ENTRY_Name, ENTRY_Emails, ENTRY_Phone, ENTRY_Notes
         FROM CB_Book_Entry
         WHERE ENTRY_Book_Parent_UUID = ?
         ORDER BY ENTRY_ID'
    );
    $stmt->execute([$book_uuid]);
    $entries = $stmt->fetchAll();
    $stmt = null;
    $connection = null;

    foreach ($entries as &$entry) {
        $entry['photo_count'] = count(list_entry_photos($book_uuid, (string) $entry['ENTRY_UUID']));
    }
    unset($entry);
    return $entries;
}

/* *********************************************************** */
/* Function:    summarize_entry_notes                          */
/* Description: The start of an entry's message for the        */
/*              entries table: line breaks become spaces and   */
/*              anything past $max_length is cut, with "…".    */
/* Returns:     The summary (not HTML-escaped).                */
/* *********************************************************** */
function summarize_entry_notes(?string $notes, int $max_length = 36): string {
    $text = trim(preg_replace('/\s+/u', ' ', (string) $notes));
    if (mb_strlen($text, 'UTF-8') <= $max_length) {
        return $text;
    }
    return rtrim(mb_substr($text, 0, $max_length, 'UTF-8')) . '…';
}

/* *********************************************************** */
/* Function:    is_uuid                                        */
/* Description: Whether a string looks like the UUIDs that     */
/*              generate_uuid_v4() makes.                      */
/* *********************************************************** */
function is_uuid(string $value): bool {
    return (bool) preg_match('/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/', $value);
}

/* *********************************************************** */
/* Function:    entry_photo_directory                          */
/* Description: The full path of an entry's photo folder.     */
/* Returns:     books/<book uuid>/pictures/<entry uuid>        */
/* *********************************************************** */
function entry_photo_directory(string $book_uuid, string $entry_uuid): string {
    return book_directory_path(basename($book_uuid)) . '/' . BOOK_PICTURES_DIR_NAME . '/' . basename($entry_uuid);
}

/* *********************************************************** */
/* Function:    list_entry_photos                              */
/* Description: An entry's photo filenames, in number order    */
/*              (photo-1.jpg, photo-2.png, ..., photo-10.jpg). */
/* Returns:     The filenames (no folder), or [] if none.      */
/* *********************************************************** */
function list_entry_photos(string $book_uuid, string $entry_uuid): array {
    $files = array_map('basename', glob(entry_photo_directory($book_uuid, $entry_uuid) . '/photo-*') ?: []);
    natsort($files);
    return array_values($files);
}

/* *********************************************************** */
/* Function:    entry_photo_url                                */
/* Description: The address of one of an entry's photos,       */
/*              relative to the site, with the file's time     */
/*              added so browsers fetch a changed photo again. */
/* *********************************************************** */
function entry_photo_url(string $book_uuid, string $entry_uuid, string $filename): string {
    $path = entry_photo_directory($book_uuid, $entry_uuid) . '/' . basename($filename);
    return BOOKS_DIR_NAME . '/' . rawurlencode($book_uuid) . '/' . BOOK_PICTURES_DIR_NAME . '/' . rawurlencode($entry_uuid)
        . '/' . rawurlencode(basename($filename)) . '?v=' . (is_file($path) ? filemtime($path) : 0);
}

/* *********************************************************** */
/* Function:    find_entry                                     */
/* Description: Looks up one entry - only if it belongs to the */
/*              given book.                                    */
/* Inputs:      $book_uuid, $entry_uuid - the two UUIDs.       */
/* Returns:     The entry in the same shape as                 */
/*              clean_entry_form() (to fill the edit form),    */
/*              plus 'uuid', or null if there's no such entry. */
/* *********************************************************** */
function find_entry(string $book_uuid, string $entry_uuid): ?array {
    if (!is_uuid($book_uuid) || !is_uuid($entry_uuid)) {
        return null;
    }
    $connection = Create_SQL_PHP_DataObject();
    $stmt = $connection->prepare(
        'SELECT ENTRY_UUID, ENTRY_Name, ENTRY_Emails, ENTRY_Street_Address, ENTRY_City, ENTRY_State,
                ENTRY_Zip, ENTRY_Phone, ENTRY_Notes
         FROM CB_Book_Entry
         WHERE ENTRY_UUID = ? AND ENTRY_Book_Parent_UUID = ?'
    );
    $stmt->execute([$entry_uuid, $book_uuid]);
    $row = $stmt->fetch();
    $stmt = null;
    $connection = null;
    if (!$row) {
        return null;
    }
    return [
        'uuid'   => $row['ENTRY_UUID'],
        'name'   => (string) $row['ENTRY_Name'],
        'street' => (string) $row['ENTRY_Street_Address'],
        'city'   => (string) $row['ENTRY_City'],
        'state'  => (string) $row['ENTRY_State'],
        'zip'    => (string) $row['ENTRY_Zip'],
        'phone'  => (string) $row['ENTRY_Phone'],
        'emails' => clean_entry_emails(explode(',', (string) $row['ENTRY_Emails'])),
        'notes'  => (string) $row['ENTRY_Notes'],
    ];
}

/* *********************************************************** */
/* Function:    update_entry                                   */
/* Description: Saves an admin's changes to an entry: the      */
/*              fields, photos to remove and new photos to     */
/*              add (at most ENTRY_PHOTOS_MAX_COUNT in all).   */
/*              New photos are saved first and removed again   */
/*              if the row can't be saved; removed photos are  */
/*              only deleted once it is. The caller must check */
/*              that the user may manage the book.             */
/* Inputs:      $book_uuid, $entry_uuid - the two UUIDs.       */
/*              $form - the submitted fields ($_POST).         */
/*              $photo_files - $_FILES['entry_photos'], or     */
/*              null. $remove - filenames of photos to remove. */
/* Returns:     ['success' => bool, 'error' => string,         */
/*               'entry' => the cleaned fields]                */
/* *********************************************************** */
function update_entry(string $book_uuid, string $entry_uuid, array $form, ?array $photo_files, array $remove): array {
    $entry = clean_entry_form($form);
    $fail = function (string $error) use (&$entry): array {
        return ['success' => false, 'error' => $error, 'entry' => $entry];
    };

    $error = validate_entry($entry);
    if ($error !== '') {
        return $fail($error);
    }
    $existing = list_entry_photos($book_uuid, $entry_uuid);
    $remove   = array_values(array_intersect($existing, $remove));  // only this entry's own photos
    $uploads  = check_entry_photo_uploads($photo_files);
    if ($uploads['error'] !== '') {
        return $fail($uploads['error']);
    }
    $kept = count($existing) - count($remove);
    if ($kept + count($uploads['photos']) > ENTRY_PHOTOS_MAX_COUNT) {
        return $fail('An entry can have at most ' . ENTRY_PHOTOS_MAX_COUNT . ' photos. With the ' . $kept
            . ' it\'s keeping, you can add ' . max(0, ENTRY_PHOTOS_MAX_COUNT - $kept) . ' more.');
    }

    // New photos continue the numbering: photo-4.jpg after photo-3.jpg.
    $dir     = entry_photo_directory($book_uuid, $entry_uuid);
    $added   = [];
    $next    = 1;
    foreach ($existing as $file) {
        if (preg_match('/^photo-(\d+)\./', $file, $m)) {
            $next = max($next, (int) $m[1] + 1);
        }
    }
    if ($uploads['photos']) {
        $pictures_path = dirname($dir);
        if ((!is_dir($pictures_path) && !mkdir($pictures_path, 0755)) || (!is_dir($dir) && !mkdir($dir, 0755))) {
            error_log('ContactBook: could not create entry photo directory ' . $dir);
            return $fail('The photos could not be saved. Please try again.');
        }
        foreach ($uploads['photos'] as $photo) {
            $saved = save_book_photo($photo['tmp'], $photo['type'], $dir, 'photo-' . $next++);
            if ($saved === '') {
                error_log('ContactBook: could not save a new photo for entry ' . $entry_uuid);
                foreach ($added as $file) {
                    unlink($dir . '/' . $file);
                }
                return $fail('The photos could not be saved. Please try again, or try different photos.');
            }
            $added[] = $saved;
        }
    }

    $null_if_empty = function (string $value): ?string {
        return ($value === '') ? null : $value;
    };
    try {
        $connection = Create_SQL_PHP_DataObject();
        $stmt = $connection->prepare(
            'UPDATE CB_Book_Entry
             SET ENTRY_Name = ?, ENTRY_Emails = ?, ENTRY_Street_Address = ?, ENTRY_City = ?, ENTRY_State = ?,
                 ENTRY_Zip = ?, ENTRY_Phone = ?, ENTRY_Notes = ?
             WHERE ENTRY_UUID = ? AND ENTRY_Book_Parent_UUID = ?'
        );
        $stmt->execute([
            $entry['name'],
            $null_if_empty(implode(ENTRY_EMAIL_SEPARATOR, $entry['emails'])),
            $null_if_empty($entry['street']),
            $null_if_empty($entry['city']),
            $null_if_empty($entry['state']),
            $null_if_empty($entry['zip']),
            $null_if_empty($entry['phone']),
            $null_if_empty($entry['notes']),
            $entry_uuid,
            $book_uuid,
        ]);
        $stmt = null;
        $connection = null;
    } catch (PDOException $e) {
        error_log('ContactBook: could not update entry ' . $entry_uuid . ': ' . $e->getMessage());
        foreach ($added as $file) {
            unlink($dir . '/' . $file);
        }
        return $fail('The entry could not be saved. Please try again.');
    }

    foreach ($remove as $file) {
        unlink($dir . '/' . $file);
    }
    if (is_dir($dir) && list_entry_photos($book_uuid, $entry_uuid) === []) {
        rmdir($dir);  // no photos left
    }
    return ['success' => true, 'error' => '', 'entry' => $entry];
}

